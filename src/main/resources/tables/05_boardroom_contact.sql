-- Run manually against the target database, in filename order (01, 02, ...) — later
-- tables reference earlier ones by foreign key. See README.md in this directory.
--
-- Depends on: boardrooms

CREATE TABLE IF NOT EXISTS public.boardroom_contact (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    boardroom_id BIGINT REFERENCES public.boardrooms(id),
    communication_method VARCHAR(255) CHECK (communication_method IN ('PHONE_EXTENSION', 'MOBILE')),
    contact VARCHAR(255),
    identifier VARCHAR(255) UNIQUE,
    tag VARCHAR(255) NOT NULL UNIQUE,
    archived BOOLEAN NOT NULL,
    deleted BOOLEAN,
    created_at TIMESTAMP(6),
    created_by BIGINT,
    occurred_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    updated_by BIGINT
);
