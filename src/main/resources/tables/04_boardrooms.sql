-- Run manually against the target database, in filename order (01, 02, ...) — later
-- tables reference earlier ones by foreign key. See README.md in this directory.
--
-- Depends on: users
--
-- administrator_id is a plain (non-unique) foreign key: a boardroom's administrator is one
-- user, but one user may administer more than one boardroom.

CREATE TABLE IF NOT EXISTS public.boardrooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    capacity INT NOT NULL,
    internet_enabled BOOLEAN NOT NULL,
    "locked" BOOLEAN NOT NULL,
    administrator_id BIGINT REFERENCES public.users(id),
    description VARCHAR(1000) NOT NULL,
    centre VARCHAR(255),
    department VARCHAR(255),
    email VARCHAR(255) UNIQUE,
    identifier VARCHAR(255) UNIQUE,
    meeting_type_supported VARCHAR(255),
    picture VARCHAR(255),
    tag VARCHAR(255) NOT NULL UNIQUE,
    archived BOOLEAN NOT NULL,
    deleted BOOLEAN,
    created_at TIMESTAMP(6),
    created_by BIGINT,
    occurred_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    updated_by BIGINT
);
